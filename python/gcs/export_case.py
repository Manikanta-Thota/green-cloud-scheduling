"""Export a generated instance, with Python's FCFS result, in the testdata text format.

The Java SelfCheck reads the file and must reproduce Python's objectives and baseline assignments,
which checks Java/Python parity on a realistic instance:

    python -m gcs.export_case --scenario 3 --rep 0 --out ../testdata/parity_case.txt
"""
from __future__ import annotations
import argparse
from .baselines import fcfs, min_min
from .model import evaluate
from .scenarios import instance_seed, load_config, scenario_matrix
from .workload import generate


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenario", type=int, default=0)
    ap.add_argument("--rep", type=int, default=0)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    cfg = load_config()
    sc = scenario_matrix(cfg)[a.scenario]
    inst = generate(cfg, sc, instance_seed(cfg, sc["scenario_id"], a.rep))
    assign_f, assign_m = fcfs(inst), min_min(inst)
    obj = evaluate(inst, assign_f)
    lines = [f"# parity case from scenario {sc} replicate {a.rep}; generated by gcs.export_case", ""]
    for v in range(inst.n_vms):
        lines.append(f"vm {float(inst.mips[v])!r} {float(inst.price[v])!r} {int(inst.host_of[v])}")
    for h in range(len(inst.p_idle)):
        lines.append(f"host {h} {float(inst.p_idle[h])!r} {float(inst.p_max[h])!r}")
    for t in range(inst.n_tasks):
        lines.append(f"task {float(inst.length[t])!r} {float(inst.arrival[t])!r} {float(inst.deadline[t])!r}")
    lines.append("assign " + " ".join(map(str, assign_f)))
    for k in ("makespan", "energy", "cost", "imbalance", "sla"):
        lines.append(f"expect {k} {float(obj[k])!r}")
    lines.append("expect_fcfs " + " ".join(map(str, assign_f)))
    lines.append("expect_minmin " + " ".join(map(str, assign_m)))
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {a.out}: {inst.n_tasks} tasks, {inst.n_vms} VMs")


if __name__ == "__main__":
    main()
