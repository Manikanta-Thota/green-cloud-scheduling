"""Write instances in the shared text format read by the Java side (gcs.core.CaseFile).

As a script it exports a parity case: a generated instance with Python's objectives for the FCFS
schedule and both baseline assignments. The Java SelfCheck must reproduce all of them:

    python -m gcs.export_case --scenario 4 --rep 0 --out ../testdata/parity_case.txt
"""
from __future__ import annotations
import argparse
from .baselines import fcfs, min_min
from .model import Instance, evaluate
from .scenarios import instance_seed, load_config, scenario_matrix
from .workload import generate


def write_case(path: str, inst: Instance, header: str = "", assign=None, expect: dict | None = None,
               expect_assign: dict | None = None, meta: dict | None = None, seeds: dict | None = None):
    lines = [f"# {header}", ""] if header else []
    for k, v in (meta or {}).items():
        lines.append(f"meta {k} {v}")
    for k, v in (seeds or {}).items():
        lines.append(f"seed {k} {v}")
    for v in range(inst.n_vms):
        lines.append(f"vm {float(inst.mips[v])!r} {float(inst.price[v])!r} {int(inst.host_of[v])}")
    for h in range(len(inst.p_idle)):
        lines.append(f"host {h} {float(inst.p_idle[h])!r} {float(inst.p_max[h])!r}")
    for t in range(inst.n_tasks):
        lines.append(f"task {float(inst.length[t])!r} {float(inst.arrival[t])!r} {float(inst.deadline[t])!r} {int(inst.rank[t])}")
    for t, ps in enumerate(inst.preds):
        if len(ps):
            lines.append(f"pred {t} " + " ".join(map(str, ps)))
    if assign is not None:
        lines.append("assign " + " ".join(map(str, assign)))
    for k, v in (expect or {}).items():
        lines.append(f"expect {k} {float(v)!r}")
    for k, v in (expect_assign or {}).items():
        lines.append(f"expect_{k} " + " ".join(map(str, v)))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenario", type=int, default=4)
    ap.add_argument("--rep", type=int, default=0)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    cfg = load_config()
    sc = scenario_matrix(cfg)[a.scenario]
    inst = generate(cfg, sc, instance_seed(cfg, sc["scenario_id"], a.rep))
    assign_f, assign_m = fcfs(inst), min_min(inst)
    obj = evaluate(inst, assign_f)
    write_case(a.out, inst, f"parity case from scenario {sc} replicate {a.rep}; generated by gcs.export_case",
               assign=assign_f, expect={k: obj[k] for k in ("makespan", "energy", "cost", "imbalance", "sla")},
               expect_assign={"fcfs": assign_f, "minmin": assign_m})
    print(f"wrote {a.out}: {inst.n_tasks} tasks, {inst.n_vms} VMs")


if __name__ == "__main__":
    main()
